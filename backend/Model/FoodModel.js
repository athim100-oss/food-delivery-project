const mongoose = require("mongoose");
const FoodSchema = new mongoose.Schema(
  {
    foodname: {
      type: String,
      required: true,
    },
    description: {
      type: String,
      required: true,
    },
    price: {
      type: Number,
      required: true,
    },
    image: {
      type: String,
      required: true,
    },
    category: {
      type: String,
      required: true,
    },
    available: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  },
);
const Food = mongoose.model("Food", FoodSchema);
module.exports = Food;
